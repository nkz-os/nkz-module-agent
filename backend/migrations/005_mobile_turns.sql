-- =============================================================================
-- 005 — Mobile channel: background turns submitted by the mobile app
-- =============================================================================
-- One row per turn the mobile app submits. The app creates the row (state
-- 'queued'), a background task runs the turn and writes the outcome, and the
-- app polls the row by turn_id. Rows are append-only history of mobile turns.
--
-- Isolation is the full key, not row-level security (this table deliberately
-- has none, same reasoning as agent_conversation_state in 003): turns are
-- private to one account, and every statement in the mobile code path
-- qualifies BOTH tenant_id and user_id; the row is never read by turn_id alone.
--
-- client_turn_id is generated by the app and is the idempotency key for a
-- retried submit. It is unique per (tenant_id, user_id), not per tenant:
-- two users' apps generate ids independently and must never collide or, worse,
-- let one user's retry resolve to another user's turn.
-- =============================================================================

CREATE TABLE IF NOT EXISTS agent_module.agent_mobile_turns (
    turn_id         UUID        PRIMARY KEY DEFAULT gen_random_uuid(),
    tenant_id       TEXT        NOT NULL,
    user_id         TEXT        NOT NULL,
    client_turn_id  TEXT        NOT NULL,
    parcel_id       TEXT        NULL,
    lang            TEXT        NOT NULL DEFAULT 'es',
    text            TEXT        NOT NULL,
    state           TEXT        NOT NULL
                    CHECK (state IN ('queued', 'running', 'done', 'failed')),
    reply_text      TEXT        NULL,
    citations       JSONB       NOT NULL DEFAULT '[]'::jsonb,
    outcome         TEXT        NULL,
    error_code      TEXT        NULL,
    trace_id        TEXT        NOT NULL,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    started_at      TIMESTAMPTZ NULL,
    finished_at     TIMESTAMPTZ NULL,
    UNIQUE (tenant_id, user_id, client_turn_id)
);

CREATE INDEX IF NOT EXISTS agent_mobile_turns_user_created_idx
    ON agent_module.agent_mobile_turns (tenant_id, user_id, created_at DESC);

ALTER TABLE agent_module.agent_mobile_turns OWNER TO nkz_module_agent;
